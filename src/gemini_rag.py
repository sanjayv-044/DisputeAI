"""
DisputeAI Gemini RAG Engine
Generates regulatory analysis and liability advice grounded in retrieved RBI circulars.
Supports live LLM via Gemini API with deterministic fallback when API key is unconfigured.
"""

import os
import requests
from typing import List, Dict, Any

GEMINI_URL = (
    "https://generativelanguage.googleapis.com/v1beta/"
    "models/gemini-3.8-flash:generateContent"
)


def synthesize_local_regulatory_response(question: str, evidence: List[Dict[str, Any]]) -> str:
    """
    Deterministic regulatory synthesizer grounded in official RBI documents.
    Used when GEMINI_API_KEY is not configured or network is isolated.
    """
    if not evidence:
        return (
            "No direct RBI regulatory evidence could be retrieved for this dispute. "
            "Recommendation: Refer this dispute for manual banking ombudsman inspection under RBI Integrated Ombudsman Scheme 2026."
        )

    sources = set()
    historical_count = 0
    current_count = 0
    citations = []

    for item in evidence[:4]:
        src = item.get("source", "RBI Circular")
        page = item.get("page", 1)
        status = item.get("status", "unknown")
        sources.add(f"{src} (Page {page})")
        citations.append(f"- **{src}** [Page {page}] ({status.upper()}): {item.get('text', '')[:250]}...")
        if status == "historical":
            historical_count += 1
        else:
            current_count += 1

    synthesis = f"""### RBI Regulatory Grounding & Analysis

**Retrieved Official Citations:**
{chr(10).join(citations)}

**Regulatory Assessment:**
1. **Governing Framework**: Under RBI Circular *DBR.No.Leg.BC.78/09.07.005/2017-18* on *Customer Protection – Limiting Liability of Customers in Unauthorised Electronic Banking Transactions*:
   - **Zero Customer Liability** applies if the unauthorised transaction is due to contributory negligence/deficiency on the part of the bank, or third-party breach where the customer notifies the bank within 3 working days of the transaction communication.
   - **Limited Customer Liability** applies if reported within 4 to 7 working days (per transaction liability capped at ₹5,000 to ₹25,000 depending on account type).
   - **Customer Negligence**: Where loss occurred because credentials or OTP were shared, customer bears loss until reported to bank.

2. **Resolution Timelines**:
   - The bank must credit (shadow reversal) the disputed amount within 10 working days of notification.
   - Overall resolution must be completed within 90 days.

3. **Status Note**: {historical_count} historical and {current_count} current regulatory references evaluated. {f'WARNING: Trailing withdrawal status detected on {historical_count} reference(s); human review recommended.' if historical_count > 0 else 'All evaluated references active.'}

*(Generated by DisputeAI Regulatory Synthesis Engine. Configure GEMINI_API_KEY for real-time generative dialogue).*"""

    return synthesis.strip()


def generate_rag_answer(question: str, evidence: List[Dict[str, Any]], timeout: int = 20) -> str:
    """Generate regulatory answer using Gemini API or local synthesis fallback."""
    api_key = os.environ.get("GEMINI_API_KEY")

    if not api_key:
        return synthesize_local_regulatory_response(question, evidence)

    evidence_text = ""
    for item in evidence[:4]:
        evidence_text += f"""
Source: {item.get('source')}
Page: {item.get('page')}
Status: {item.get('status')}
Scope: {item.get('scope')}
Evidence: {item.get('text', '')[:1000]}
--------------------
"""

    prompt = f"""
You are DisputeAI's RBI regulatory assistant.
Answer using only the evidence provided below.

Question:
{question}

Evidence:
{evidence_text}

Instructions:
- Cite source names and page numbers explicitly.
- Never present withdrawn rules as current law without caveat.
- Distinguish historical from current evidence.
- Do not invent RBI rules or bank policies.
- Recommend human review if liability cannot be determined definitively.
"""

    try:
        response = requests.post(
            GEMINI_URL,
            params={"key": api_key},
            json={
                "contents": [
                    {"parts": [{"text": prompt}]}
                ]
            },
            timeout=timeout
        )
        response.raise_for_status()
        result = response.json()
        return result["candidates"][0]["content"]["parts"][0]["text"]
    except Exception as e:
        # Graceful fallback to deterministic local synthesizer
        return synthesize_local_regulatory_response(question, evidence)
